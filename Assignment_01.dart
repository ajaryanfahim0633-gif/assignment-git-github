void main() {
  // Creating Set A
  Set<int> setA = {1, 2, 3, 4, 5};
  // Creating Set B
  Set<int> setB = {4, 5, 6, 7, 8};
  // Printing elements of Set A using for loop
  print("Elements of Set A:");
  for (int element in setA) {
    print(element);
  }
  // Printing elements of Set B using for loop
  print("\nElements of Set B:");
  for (int element in setB) {
    print(element);
  }
}

